  export type Language = keyof typeof translations;
  
  type NestedTranslation = { [key: string]: string | NestedTranslation };

  // This flattens the nested objects into dot notation keys
  type FlattenKeys<T extends NestedTranslation, P extends string | '' = ''> = {
      [K in keyof T]: T[K] extends string
          ? `${P}${K & string}`
          : FlattenKeys<T[K] & NestedTranslation, `${P}${K & string}.`>
  }[keyof T];

  export type TranslationKey = FlattenKeys<typeof translations['en']>;
  
  // A simple interpolation function
  export const interpolate = (str: string, values: Record<string, any>): string => {
      // Basic pluralization for Russian 'members'
      if (str.includes('plural') && values.count !== undefined) {
          const count = values.count;
          const options = str.match(/one {(.*?)}|few {(.*?)}|other {(.*?)}/g);
          let result = '';
          if (options) {
              const pluralRules = new Intl.PluralRules('ru-RU');
              const category = pluralRules.select(count);
              switch(category) {
                  case 'one':
                      result = options.find(o => o.startsWith('one'))?.replace(/one {|}|\# участник/g, '').trim() || '';
                      return `${count} участник`;
                  case 'few':
                      result = options.find(o => o.startsWith('few'))?.replace(/few {|}|\# участника/g, '').trim() || '';
                       return `${count} участника`;
                  default:
                      result = options.find(o => o.startsWith('other'))?.replace(/other {|}|\# участников/g, '').trim() || '';
                       return `${count} участников`;
              }
          }
      }

      return str.replace(/{(\w+)}/g, (match, key) => {
          return values[key] !== undefined ? String(values[key]) : match;
      });
  };
  
